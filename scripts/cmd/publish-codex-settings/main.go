// publish-codex-settings exports portable preferences without local integrations or state.
package main

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/pelletier/go-toml/v2"
)

// Unlisted fields stay local, including future config additions.
var publicFields = map[string][]string{
	"": {
		"model", "project_doc_fallback_filenames", "project_doc_max_bytes",
		"approval_policy", "approvals_reviewer", "sandbox_mode", "personality",
		"service_tier", "model_reasoning_effort", "model_verbosity", "web_search",
	},
	"sandbox_workspace_write":  {"network_access", "exclude_slash_tmp", "exclude_tmpdir_env_var"},
	"shell_environment_policy": {"inherit", "exclude", "include_only", "ignore_default_excludes"},
	"tui": {
		"vim_mode_default", "notifications", "notification_method", "notification_condition",
		"status_line", "status_line_use_colors", "alternate_screen", "fullscreen_transcript",
		"raw_output_mode", "animations", "theme", "show_tooltips", "mouse_scroll_speed",
	},
	"history":  {"persistence", "max_bytes"},
	"features": {"js_repl", "terminal_resize_reflow", "multi_agent"},
}

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "publish-codex-settings:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	home, err := os.UserHomeDir()
	if err != nil {
		return err
	}
	configDir := os.Getenv("CODEX_HOME")
	if configDir == "" {
		configDir = filepath.Join(home, ".config", "codex")
	}
	in, out := filepath.Join(configDir, "config.toml"), filepath.Join(configDir, "config.public.toml")
	if len(args) == 2 {
		in, out = args[0], args[1]
	} else if len(args) != 0 {
		return errors.New("usage: publish-codex-settings [input output]")
	}
	raw, err := os.ReadFile(in)
	if err != nil {
		return err
	}
	pub, err := publicize(raw, home)
	if err != nil {
		return err
	}
	return os.WriteFile(out, pub, 0o644)
}

func publicize(raw []byte, home string) ([]byte, error) {
	var doc map[string]any
	if err := toml.Unmarshal(raw, &doc); err != nil {
		// Parser diagnostics can contain values from the local configuration.
		return nil, errors.New("入力の TOML を解析できません")
	}
	pub := make(map[string]any)
	for section, fields := range publicFields {
		source, target := doc, pub
		if section != "" {
			var ok bool
			source, ok = doc[section].(map[string]any)
			if !ok {
				continue
			}
			target = make(map[string]any)
		}
		for _, field := range fields {
			if value, ok := source[field]; ok {
				if !scalarOrList(value) {
					return nil, errors.New("公開対象に想定外のテーブルがあります")
				}
				target[field] = value
			}
		}
		if section != "" && len(target) != 0 {
			pub[section] = target
		}
	}
	if tui, ok := doc["tui"].(map[string]any); ok {
		if keymap, ok := tui["keymap"].(map[string]any); ok {
			for _, actions := range keymap {
				bindings, ok := actions.(map[string]any)
				if !ok {
					return nil, errors.New("キーバインドの形式が不正です")
				}
				for _, value := range bindings {
					if !scalarOrList(value) {
						return nil, errors.New("キーバインドに想定外のテーブルがあります")
					}
				}
			}
			if pub["tui"] == nil {
				pub["tui"] = make(map[string]any)
			}
			pub["tui"].(map[string]any)["keymap"] = keymap
		}
	}
	encoded, err := toml.Marshal(pub)
	if err != nil {
		return nil, errors.New("公開用の TOML を生成できません")
	}
	for _, term := range []string{home, filepath.Base(home), "/Users/", "/home/", "/private/", "/Volumes/", "Bearer ", "sk-"} {
		if term != "" && strings.Contains(string(encoded), term) {
			return nil, errors.New("個人パスまたは非公開の値が公開対象に残っています")
		}
	}
	return append([]byte("# Generated by: cd scripts && go run ./cmd/publish-codex-settings\n"), encoded...), nil
}

func scalarOrList(value any) bool {
	switch value := value.(type) {
	case string, bool, int64, float64:
		return true
	case []any:
		for _, item := range value {
			if !scalarOrList(item) {
				return false
			}
		}
		return true
	default:
		return false
	}
}
